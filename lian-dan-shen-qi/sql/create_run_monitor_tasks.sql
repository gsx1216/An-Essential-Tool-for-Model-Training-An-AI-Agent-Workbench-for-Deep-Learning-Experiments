CREATE TABLE IF NOT EXISTS experiment_assistant.run_monitor_tasks (
 run_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'scheduled',
 attempts BIGINT UNSIGNED NOT NULL DEFAULT 0,
 failure_count INT UNSIGNED NOT NULL DEFAULT 0,
 next_poll_at DATETIME(6) NOT NULL,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME(6) NULL,
 last_attempt_at DATETIME(6) NULL,
 last_success_at DATETIME(6) NULL,
 last_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 report_version BIGINT UNSIGNED NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 completed_at DATETIME(6) NULL,
 PRIMARY KEY(run_id),
 KEY idx_monitor_due(status,next_poll_at,run_id),
 KEY idx_monitor_expired(status,lease_until,run_id),
 CONSTRAINT fk_monitor_execution FOREIGN KEY(run_id) REFERENCES experiment_assistant.run_executions(run_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_monitor_owner FOREIGN KEY(run_id,user_id) REFERENCES experiment_assistant.experiment_runs(id,user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_monitor_status CHECK(status IN ('scheduled','running','completed','attention')),
 CONSTRAINT ck_monitor_lease CHECK((status='running' AND lease_token IS NOT NULL AND lease_until IS NOT NULL) OR (status<>'running' AND lease_token IS NULL AND lease_until IS NULL)),
 CONSTRAINT ck_monitor_failures CHECK(failure_count<=50)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
