CREATE TABLE IF NOT EXISTS experiment_assistant.event_outbox (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 run_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 event_type VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 report_version BIGINT UNSIGNED NOT NULL,
 report_json MEDIUMTEXT COLLATE utf8mb4_bin NOT NULL,
 report_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
 attempts BIGINT UNSIGNED NOT NULL DEFAULT 0,
 failure_count INT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(6) NOT NULL,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME(6) NULL,
 redis_message_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 last_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(6) NOT NULL,
 sent_at DATETIME(6) NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_outbox_source(id,user_id,run_id,report_version),
 UNIQUE KEY uq_outbox_report(event_type,run_id,report_version),
 KEY idx_outbox_due(status,next_attempt_at,id),
 KEY idx_outbox_expired(status,lease_until,id),
 KEY idx_outbox_run_owner(run_id,user_id,created_at,id),
 CONSTRAINT fk_outbox_run FOREIGN KEY(run_id,user_id) REFERENCES experiment_assistant.experiment_runs(id,user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_outbox_event CHECK(event_type='training.report_ready' AND report_version>0),
 CONSTRAINT ck_outbox_snapshot CHECK(JSON_VALID(report_json) AND OCTET_LENGTH(report_json)<=131072),
 CONSTRAINT ck_outbox_status CHECK(status IN ('pending','sending','sent','received','attention')),
 CONSTRAINT ck_outbox_lease CHECK((status='sending' AND lease_token IS NOT NULL AND lease_until IS NOT NULL) OR (status<>'sending' AND lease_token IS NULL AND lease_until IS NULL))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
