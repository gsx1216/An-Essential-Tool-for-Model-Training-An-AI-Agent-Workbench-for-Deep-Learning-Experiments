SELECT cc.CHECK_CLAUSE FROM information_schema.TABLE_CONSTRAINTS AS tc
JOIN information_schema.CHECK_CONSTRAINTS AS cc ON cc.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA AND cc.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
WHERE tc.TABLE_SCHEMA='experiment_assistant' AND tc.TABLE_NAME='agent_tasks' AND tc.CONSTRAINT_NAME='ck_agent_task_name';
