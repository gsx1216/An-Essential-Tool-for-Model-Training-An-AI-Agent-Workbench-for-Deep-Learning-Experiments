CREATE TABLE IF NOT EXISTS experiment_assistant.chat_training_plans (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 session_id CHAR(32) NOT NULL,
 prepared_turn_id CHAR(32) NOT NULL,
 launch_turn_id CHAR(32) NULL,
 task_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 snapshot_json TEXT COLLATE utf8mb4_bin NOT NULL,
 snapshot_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 run_request_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 run_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(6) NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uq_training_plan_owner(id,user_id),
 UNIQUE KEY uq_training_plan_turn(session_id,prepared_turn_id),
 UNIQUE KEY uq_training_launch_turn(session_id,launch_turn_id),
 UNIQUE KEY uq_training_plan_request(user_id,run_request_id),
 KEY idx_training_plan_session(session_id,created_at,id),
 CONSTRAINT fk_training_plan_task FOREIGN KEY(task_id,user_id) REFERENCES experiment_assistant.training_tasks(id,user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_training_plan_session FOREIGN KEY(session_id,user_id) REFERENCES experiment_assistant.chat_sessions(id,user_id) ON DELETE CASCADE ON UPDATE RESTRICT,
 CONSTRAINT fk_training_plan_prepared FOREIGN KEY(session_id,prepared_turn_id) REFERENCES experiment_assistant.chat_turns(session_id,id) ON DELETE CASCADE ON UPDATE RESTRICT,
 CONSTRAINT fk_training_plan_launch FOREIGN KEY(session_id,launch_turn_id) REFERENCES experiment_assistant.chat_turns(session_id,id) ON DELETE CASCADE ON UPDATE RESTRICT,
 CONSTRAINT fk_training_plan_run FOREIGN KEY(run_id,user_id) REFERENCES experiment_assistant.experiment_runs(id,user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_training_plan_snapshot CHECK(JSON_VALID(snapshot_json) AND OCTET_LENGTH(snapshot_json)<=32768)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
