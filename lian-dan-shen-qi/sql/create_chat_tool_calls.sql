CREATE TABLE IF NOT EXISTS experiment_assistant.chat_tool_calls (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 session_id CHAR(32) NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 turn_id CHAR(32) NOT NULL,
 attempt_id CHAR(32) NOT NULL,
 call_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 call_index TINYINT UNSIGNED NOT NULL,
 tool_name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 arguments_json TEXT COLLATE utf8mb4_bin NOT NULL,
 outcome VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 result_meta_json TEXT COLLATE utf8mb4_bin NOT NULL,
 duration_ms INT UNSIGNED NOT NULL,
 created_at DATETIME(6) NOT NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uq_chat_tool_call(attempt_id,call_id),
 UNIQUE KEY uq_chat_tool_index(attempt_id,call_index),
 KEY idx_chat_tool_session_id(session_id,id),
 CONSTRAINT fk_chat_tool_session FOREIGN KEY(session_id,user_id) REFERENCES experiment_assistant.chat_sessions(id,user_id) ON DELETE CASCADE ON UPDATE RESTRICT,
 CONSTRAINT fk_chat_tool_turn FOREIGN KEY(session_id,turn_id) REFERENCES experiment_assistant.chat_turns(session_id,id) ON DELETE CASCADE ON UPDATE RESTRICT,
 CONSTRAINT ck_chat_tool_index CHECK(call_index BETWEEN 1 AND 4),
 CONSTRAINT ck_chat_tool_args CHECK(JSON_VALID(arguments_json) AND OCTET_LENGTH(arguments_json)<=2048),
 CONSTRAINT ck_chat_tool_meta CHECK(JSON_VALID(result_meta_json) AND OCTET_LENGTH(result_meta_json)<=24576)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
