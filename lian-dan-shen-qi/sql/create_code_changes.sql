CREATE TABLE IF NOT EXISTS experiment_assistant.code_changes (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 run_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 suggestion_task_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 suggestion_index INT UNSIGNED NOT NULL,
 request_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 origin_session_id CHAR(32) NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_json MEDIUMTEXT COLLATE utf8mb4_bin NOT NULL,
 source_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 plan_json MEDIUMTEXT COLLATE utf8mb4_bin NULL,
 plan_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 result_json MEDIUMTEXT COLLATE utf8mb4_bin NULL,
 error_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME(6) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_code_change_request(user_id,request_id),
 UNIQUE KEY uq_code_change_owner(id,user_id),
 KEY idx_code_change_run(run_id,user_id,created_at,id),
 KEY idx_code_change_session(user_id,origin_session_id,created_at,id),
 CONSTRAINT fk_code_change_run FOREIGN KEY(run_id,user_id) REFERENCES experiment_assistant.experiment_runs(id,user_id) ON DELETE RESTRICT,
 CONSTRAINT fk_code_change_suggestion FOREIGN KEY(suggestion_task_id) REFERENCES experiment_assistant.suggestion_results(task_id) ON DELETE RESTRICT,
 CONSTRAINT ck_code_change_status CHECK(status IN ('planning','ready','applying','applied','checks_failed','attention','conflict')),
 CONSTRAINT ck_code_change_index CHECK(suggestion_index BETWEEN 1 AND 3),
 CONSTRAINT ck_code_change_source CHECK(JSON_VALID(source_json) AND OCTET_LENGTH(source_json)<=65536),
 CONSTRAINT ck_code_change_plan CHECK(plan_json IS NULL OR JSON_VALID(plan_json) AND OCTET_LENGTH(plan_json)<=24576),
 CONSTRAINT ck_code_change_result CHECK(result_json IS NULL OR JSON_VALID(result_json) AND OCTET_LENGTH(result_json)<=131072),
 CONSTRAINT ck_code_change_lease CHECK((status IN ('planning','applying') AND lease_token IS NOT NULL AND lease_until IS NOT NULL) OR (status NOT IN ('planning','applying') AND lease_token IS NULL AND lease_until IS NULL))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
