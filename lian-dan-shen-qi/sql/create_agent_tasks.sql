CREATE TABLE IF NOT EXISTS experiment_assistant.agent_tasks (
 id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 run_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 event_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 agent_name VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 report_version BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'queued',
 created_at DATETIME(6) NOT NULL,
 attempts BIGINT UNSIGNED NOT NULL DEFAULT 0,
 attempts_in_cycle INT UNSIGNED NOT NULL DEFAULT 0,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME(6) NULL,
 next_attempt_at DATETIME(6) NULL,
 last_error_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NULL,
 started_at DATETIME(6) NULL,
 finished_at DATETIME(6) NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_agent_event(agent_name,event_id),
 KEY idx_agent_tasks_owner(run_id,user_id,created_at,id),
 KEY idx_agent_tasks_due(agent_name,status,created_at,id),
 KEY idx_analysis_due(status,next_attempt_at,id),
 KEY idx_analysis_lease(status,lease_until,id),
 CONSTRAINT fk_agent_task_event FOREIGN KEY(event_id,user_id,run_id,report_version) REFERENCES experiment_assistant.event_outbox(id,user_id,run_id,report_version) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_agent_task_run FOREIGN KEY(run_id,user_id) REFERENCES experiment_assistant.experiment_runs(id,user_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_agent_task_name CHECK(agent_name IN ('analysis','suggestion')),
 CONSTRAINT ck_agent_task_state CHECK(status IN ('queued','running','succeeded','failed','attention')),
 CONSTRAINT ck_agent_task_version CHECK(report_version>0),
 CONSTRAINT ck_analysis_lease CHECK((status='running' AND lease_token IS NOT NULL AND lease_until IS NOT NULL) OR (status<>'running' AND lease_token IS NULL AND lease_until IS NULL))
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
